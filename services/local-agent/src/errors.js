// 统一错误模型：HTTP 层错误码 + Agent 七类归一化错误（算法说明书第 11 节 / 架构 11.4）。
// 所有错误响应形状稳定：{ error: { code, message, details? } }，不随异常类型漂移。

export class ApiError extends Error {
  /**
   * @param {number} status HTTP 状态码
   * @param {string} code 稳定错误码（机器可读）
   * @param {string} message 用户可读信息（中文）
   * @param {object} [details] 开发者诊断上下文（不得含密钥/原始数据全文）
   */
  constructor(status, code, message, details) {
    super(message)
    this.name = 'ApiError'
    this.status = status
    this.code = code
    if (details !== undefined) this.details = details
  }

  toBody() {
    const body = { error: { code: this.code, message: this.message } }
    if (this.details !== undefined) body.error.details = this.details
    return body
  }
}

